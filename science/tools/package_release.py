#!/usr/bin/env python3
"""Build or verify an isolated, answer-key-free review package; never start a run."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

# Initial distribution verification must not create unlisted bytecode files.
sys.dont_write_bytecode = True
from leakage_guard import REGISTERED_FACING_FILES, registered_leakage_errors

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "RELEASE_MANIFEST.json"
READINESS = "RELEASE_READINESS.json"
CHANGE_REGISTER = "NEXT_SWEEP_CHANGE_REGISTER.json"
ACCEPTANCE_KEYS = ("software", "scientific_routes", "native_lifecycle", "persistence_scale", "distribution", "portability")


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def operative_input_hashes(root: Path) -> dict[str, str]:
    """Bind readiness to the actual operative inputs, excluding its own receipt."""
    return {name: digest(root / name) for name in REGISTERED_FACING_FILES if name != READINESS}


def release_inventory_errors(root: Path, *, distribution: bool = False) -> list[str]:
    """Verify the delivered inventory and explicitly permit local runtime state.

    A pristine distribution contains only allowlisted files, its manifest and
    empty run/output directories. Runtime verification also admits the locally
    bootstrapped environment, generated bytecode and the recipient's own records.
    """
    allowed_files = set(REGISTERED_FACING_FILES) | {MANIFEST}
    allowed_dirs = {"runs", "outputs", "outputs/consolidated"}
    for name in allowed_files:
        allowed_dirs.update(parent.as_posix() for parent in Path(name).parents if parent != Path("."))
    errors: list[str] = []
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix()
        parts = path.relative_to(root).parts
        runtime = not distribution and (parts[0] in {".venv", "runs"}
            or relative.startswith("outputs/consolidated/")
            or (len(parts) >= 3 and parts[:2] == ("outputs", "handoffs")
                and re.fullmatch(r"[A-Za-z0-9._-]+", parts[2])
                and (len(parts) == 3 or (len(parts) == 4 and parts[3] in {
                    "authored_input.json", "reading_handoff.json", "reading_guide.md", "input_manifest.json"})))
            or (len(parts) == 3 and parts[:2] == ("outputs", "human_review")
                and parts[2] in {"decision_log.jsonl", "golden_primary_support.json"})
            or (len(parts) == 3 and parts[0:2] == ("tools", "__pycache__")
                and parts[2].endswith(".pyc")
                and parts[2].split(".", 1)[0] + ".py" in {Path(name).name for name in allowed_files if name.startswith("tools/")}))
        if path.is_symlink():
            if not distribution and parts[0] == ".venv" and len(parts) > 1:
                continue  # Standard venv interpreter links are local runtime.
            errors.append(f"release inventory: symlinked path {relative}")
            continue
        if runtime:
            continue
        if path.is_dir():
            if relative in allowed_dirs or (not distribution and relative in {".venv", "tools/__pycache__", "outputs/handoffs", "outputs/human_review"}):
                continue
        elif path.is_file() and relative in allowed_files:
            continue
        errors.append(f"release inventory: unexpected distributed path {relative}")
    return errors


def release_readiness_errors(root: Path) -> list[str]:
    """Fail closed on missing or unfinished preparation state.

    The source change register is kept out of the reviewer package; its open
    obligations must nevertheless stop creation of that package.
    """
    errors: list[str] = []
    try:
        readiness = json.loads((root / READINESS).read_text(encoding="utf-8"))
        if not isinstance(readiness, dict):
            raise ValueError("readiness must be an object")
    except (OSError, ValueError) as exc:
        return [f"release readiness missing or invalid: {exc}"]
    if readiness.get("status") != "ready":
        errors.append("release readiness is not ready")
    if readiness.get("status") == "ready":
        acceptance = readiness.get("acceptance")
        if not isinstance(acceptance, dict) or set(acceptance) != set(ACCEPTANCE_KEYS):
            errors.append("release readiness lacks the six named acceptance receipts")
        else:
            for key, item in acceptance.items():
                if (not isinstance(item, dict) or item.get("status") != "passed"
                        or not re.fullmatch(r"[0-9a-f]{64}", str(item.get("receipt_sha256") or ""))):
                    errors.append(f"release readiness acceptance {key} is not a passed hash-bound receipt")
        try:
            if readiness.get("operative_inputs_sha256") != operative_input_hashes(root):
                errors.append("release readiness evidence is not bound to the current operative inputs")
        except OSError as exc:
            errors.append(f"release readiness cannot bind operative inputs: {exc}")
    try:
        import yaml
        config = yaml.safe_load((root / "config.yaml").read_text(encoding="utf-8"))
        for key in ("protocol_version", "package_version", "schema_version"):
            if readiness.get(key) != config.get(key):
                errors.append(f"release readiness {key} differs from config")
            value = config.get(key)
            if not isinstance(value, str) or re.search(r"(?:candidate|draft|alpha|beta|pre-freeze|(?:^|[-.])rc\d*)", value, re.I):
                errors.append(f"release {key} must be a final version, not a candidate label")
        if config.get("registration_status") not in {"frozen", "preregistered", "registered"}:
            errors.append("release registration_status must be frozen/registered")
        # Check only current front matter, not historical candidate discussions.
        for name in ("PROTOCOL.md", "AGENTS.md", "README.md", "queries.md"):
            lines = (root / name).read_text(encoding="utf-8").splitlines()[:12]
            statuses = [line for line in lines if line.startswith(("**Status:**", "**Registration status:**"))]
            if not statuses or any(re.search(r"pre-freeze|candidate|prohibited|cannot start", line, re.I) for line in statuses):
                errors.append(f"{name}: current status still prohibits a registered release")
        version_line = next((line for line in (root / "PROTOCOL.md").read_text(encoding="utf-8").splitlines()[:12] if line.startswith("**Version:**")), "")
        if version_line.removeprefix("**Version:**").strip() != config.get("protocol_version"):
            errors.append("PROTOCOL.md: current version header differs from release config")
    except (OSError, ValueError, AttributeError, ImportError) as exc:
        errors.append(f"release readiness cannot verify config: {exc}")
    register_path = root / CHANGE_REGISTER
    if register_path.exists():
        try:
            register = json.loads(register_path.read_text(encoding="utf-8"))
            if not isinstance(register, dict):
                raise ValueError("register must be an object")
            if register.get("blocks_next_package_release") or register.get("blocks_next_protocol_freeze") or any(
                item.get("status") != "resolved" for item in register.get("required_changes", [])
            ):
                errors.append("release blocked by unresolved next-sweep change register")
        except (OSError, ValueError, TypeError, AttributeError) as exc:
            errors.append(f"next-sweep change register invalid: {exc}")
    return errors


def verify_release(root: Path, *, distribution: bool = False,
                   pre_freeze_diagnostic: bool = False) -> list[str]:
    """Check the complete allowlist, not merely whatever a manifest happens to name."""
    try:
        manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
        files = manifest["files"]
        if not isinstance(files, dict) or set(files) != set(REGISTERED_FACING_FILES):
            return ["release manifest: file set differs from registered-facing allowlist"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return [f"release manifest: unavailable or malformed ({exc})"]
    errors = []
    purpose = manifest.get("purpose", "registered-release")
    if not isinstance(purpose, str) or purpose not in {"registered-release", "pre-freeze-diagnostic"}:
        errors.append("release manifest: unknown package purpose")
    if pre_freeze_diagnostic:
        if purpose != "pre-freeze-diagnostic":
            errors.append("diagnostic verification requires an explicitly diagnostic package")
        try:
            if json.loads((root / READINESS).read_text(encoding="utf-8")).get("status") != "blocked":
                errors.append("diagnostic package must retain truthful blocked readiness; build final delivery separately")
        except (OSError, ValueError, AttributeError) as exc:
            errors.append(f"diagnostic readiness record is malformed: {exc}")
    elif purpose == "pre-freeze-diagnostic":
        errors.append("diagnostic package is prohibited for registered execution/distribution; use explicit diagnostic verification")
    errors.extend(release_inventory_errors(root, distribution=distribution))
    for relative in REGISTERED_FACING_FILES:
        path = root / relative
        if path.is_symlink() or not path.is_file():
            errors.append(f"release manifest: missing or symlinked input {relative}")
        elif digest(path) != files[relative]:
            errors.append(f"release manifest: hash mismatch for {relative}")
    if not pre_freeze_diagnostic:
        errors.extend(release_readiness_errors(root))
    return errors


def build_release(root: Path, destination: Path, *, pre_freeze_diagnostic: bool = False) -> None:
    if destination.exists():
        raise ValueError(f"refusing existing release destination: {destination}")
    if not pre_freeze_diagnostic:
        readiness_errors = release_readiness_errors(root)
        if readiness_errors:
            raise ValueError("\n".join(readiness_errors))
    else:
        # Keep real blocked readiness in the package. Never manufacture a ready
        # attestation merely to obtain isolated inputs for pre-freeze readings.
        readiness = json.loads((root / READINESS).read_text(encoding="utf-8"))
        if not isinstance(readiness, dict) or readiness.get("status") != "blocked":
            raise ValueError("diagnostic build requires truthful blocked readiness; ready inputs use ordinary release build")
    errors = registered_leakage_errors(root)
    if errors:
        raise ValueError("\n".join(errors))
    # Capture source identity before copying and check it afterward as well.
    hashes = {name: digest(root / name) for name in REGISTERED_FACING_FILES}
    destination.mkdir(parents=True)
    for relative in REGISTERED_FACING_FILES:
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / relative, target)
    for relative in ("runs", "outputs/consolidated"):
        (destination / relative).mkdir(parents=True, exist_ok=True)
    (destination / MANIFEST).write_text(json.dumps({
        "created_at": datetime.now(timezone.utc).isoformat(),
        "identity": "SHA-256 of actual distributed inputs; not a signature or clean-commit claim",
        "purpose": "pre-freeze-diagnostic" if pre_freeze_diagnostic else "registered-release",
        "files": hashes,
    }, indent=2) + "\n", encoding="utf-8")
    errors = verify_release(destination, distribution=True, pre_freeze_diagnostic=pre_freeze_diagnostic)
    if any(digest(root / name) != value for name, value in hashes.items()):
        errors.append("source inputs changed during release creation")
    if errors:
        raise ValueError("Incomplete release; do not distribute:\n" + "\n".join(errors))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("build", "verify"))
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--destination", type=Path)
    parser.add_argument("--distribution", action="store_true", help="verify a pristine distribution; reject environments, caches and populated runs")
    parser.add_argument("--pre-freeze-diagnostic", action="store_true", help="explicit isolated validation package; prohibited for registered execution/distribution")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if args.mode == "build":
            if args.destination is None:
                parser.error("build requires --destination")
            build_release(root, args.destination.resolve(), pre_freeze_diagnostic=args.pre_freeze_diagnostic)
        else:
            errors = verify_release(root, distribution=args.distribution, pre_freeze_diagnostic=args.pre_freeze_diagnostic)
            if errors:
                raise ValueError("\n".join(errors))
    except (OSError, ValueError) as exc:
        print(f"FAIL: {exc}")
        return 1
    print(f"PASS: release {args.mode}; no run started.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
